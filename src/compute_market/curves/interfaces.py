"""Public mathematical interfaces; affine coefficients belong to a realization."""
from __future__ import annotations
from typing import Protocol, runtime_checkable, Any
import numpy as np

@runtime_checkable
class MarketModel(Protocol):
    """A coupled term structure, pricing law and physical transition law."""
    @property
    def dimension(self) -> int: ...
    @property
    def fingerprint(self) -> str: ...
    factors: tuple[str, ...]
    def value(self, name: str, t: float, x: np.ndarray, T: float) -> np.ndarray: ...
    def forward(self, name: str, t: float, x: np.ndarray, T: float) -> np.ndarray: ...
    def discount(self, t: float, x: np.ndarray, T: float) -> np.ndarray: ...
    def greeks(self, name: str, t: float, x: np.ndarray, T: float) -> tuple: ...
    def step(self, x: np.ndarray, dt: float, rng: np.random.Generator,
             measure: str = 'P') -> tuple[np.ndarray, np.ndarray]: ...
    def simulate(self, times, paths: int, seed: int = 0,
                 measure: str = 'P', initial=None) -> Any: ...

@runtime_checkable
class TradableClaim(Protocol):
    """Ex-dividend marks, actual cash events, execution and collateral."""
    name: str
    multiplier: float
    @property
    def maturity(self) -> float: ...
    @property
    def funded(self) -> bool: ...
    def mark(self, model: MarketModel, t: float, x: np.ndarray): ...
    def settlement(self, model: MarketModel, t: float, x: np.ndarray): ...
    def delta(self, model: MarketModel, t: float, x: np.ndarray): ...
    def margin(self, model: MarketModel, t: float, x: np.ndarray): ...
    def bounds(self, t: float) -> tuple[float, float]: ...
